# src/competition_params.jl
# Параметры для варианта №56

module CompetitionParams

export p_cr, N, q, τ₁, τ₂, p̃₁, p̃₂, M0₁, M0₂, tspan
export a₁, a₂, b, c₁, c₂
export case1!, case2!

# Параметры варианта
const p_cr = 45.0      # критическая стоимость (тыс. ед.)
const N = 55.0         # число потребителей (тыс. ед.)
const q = 1.0          # максимальная потребность
const τ₁ = 30.0        # длительность цикла фирмы 1
const τ₂ = 25.0        # длительность цикла фирмы 2
const p̃₁ = 9.0        # себестоимость фирмы 1 (тыс. ед.)
const p̃₂ = 11.0       # себестоимость фирмы 2 (тыс. ед.)

# Начальные условия (оборотные средства в млн. ед.)
const M0₁ = 7.5
const M0₂ = 9.5

# Временной интервал
const tspan = (0.0, 50.0)

# -------------------------------------------------------------------
# РАСЧЁТ КОЭФФИЦИЕНТОВ
# -------------------------------------------------------------------
const a₁ = p_cr / (τ₁^2 * p̃₁^2 * N * q)
const a₂ = p_cr / (τ₂^2 * p̃₂^2 * N * q)
const b = p_cr / (τ₁^2 * p̃₁^2 * τ₂^2 * p̃₂^2 * N * q)
const c₁ = (p_cr - p̃₁) / (τ₁ * p̃₁)
const c₂ = (p_cr - p̃₂) / (τ₂ * p̃₂)

# -------------------------------------------------------------------
# СЛУЧАЙ 1: Только рыночные методы конкуренции
# -------------------------------------------------------------------
function case1!(du, u, p, t)
    M₁, M₂ = u
    du[1] = M₁ - (b/c₁)*M₁*M₂ - (a₁/c₁)*M₁^2
    du[2] = (c₂/c₁)*M₂ - (b/c₁)*M₁*M₂ - (a₂/c₁)*M₂^2
    nothing
end

# -------------------------------------------------------------------
# СЛУЧАЙ 2: С учётом социально-психологических факторов
# (коэффициент перед M₁M₂ увеличен на 0.00046)
# -------------------------------------------------------------------
const delta = 0.00046

function case2!(du, u, p, t)
    M₁, M₂ = u
    du[1] = M₁ - (b/c₁ + delta)*M₁*M₂ - (a₁/c₁)*M₁^2
    du[2] = (c₂/c₁)*M₂ - (b/c₁)*M₁*M₂ - (a₂/c₁)*M₂^2
    nothing
end

end
