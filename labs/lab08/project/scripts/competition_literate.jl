# # Модель конкуренции двух фирм
#
# **Цель работы:** Исследовать динамику конкуренции двух фирм,
# производящих взаимозаменяемые товары, с использованием системы
# дифференциальных уравнений. Сравнить два случая:
# 1. Только рыночные методы конкуренции
# 2. С учётом социально-психологических факторов
#
# ## 1. Теоретическое введение
#
# Модель описывает изменение оборотных средств двух фирм
# во времени. Система уравнений в общем виде:
#
# $$
# \begin{align*}
# \frac{dM_1}{d\theta} &= M_1 - \frac{b}{c_1} M_1 M_2 - \frac{a_1}{c_1} M_1^2 \\
# \frac{dM_2}{d\theta} &= \frac{c_2}{c_1} M_2 - \frac{b}{c_1} M_1 M_2 - \frac{a_2}{c_1} M_2^2
# \end{align*}
# $$
#
# где коэффициенты определяются по формулам:
#
# $$
# a_1 = \frac{p_{cr}}{\tau_1^2 \tilde{p}_1^2 Nq}, \quad
# a_2 = \frac{p_{cr}}{\tau_2^2 \tilde{p}_2^2 Nq}, \quad
# b = \frac{p_{cr}}{\tau_1^2 \tilde{p}_1^2 \tau_2^2 \tilde{p}_2^2 Nq}
# $$
#
# $$
# c_1 = \frac{p_{cr} - \tilde{p}_1}{\tau_1 \tilde{p}_1}, \quad
# c_2 = \frac{p_{cr} - \tilde{p}_2}{\tau_2 \tilde{p}_2}
# $$
#
# ## 2. Параметры варианта №56
#
# | Параметр | Значение | Описание |
# |----------|----------|----------|
# | $p_{cr}$ | 45 | Критическая стоимость продукта (тыс. ед.) |
# | $N$ | 55 | Число потребителей (тыс. ед.) |
# | $q$ | 1 | Максимальная потребность одного человека |
# | $\tau_1$ | 30 | Длительность цикла фирмы 1 |
# | $\tau_2$ | 25 | Длительность цикла фирмы 2 |
# | $\tilde{p}_1$ | 9 | Себестоимость фирмы 1 (тыс. ед.) |
# | $\tilde{p}_2$ | 11 | Себестоимость фирмы 2 (тыс. ед.) |
# | $M_0^1$ | 7.5 | Начальные оборотные средства фирмы 1 (млн. ед.) |
# | $M_0^2$ | 9.5 | Начальные оборотные средства фирмы 2 (млн. ед.) |
#
