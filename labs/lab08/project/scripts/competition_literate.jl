# ## 8. Стационарные точки (аналитический расчёт)
#
# Стационарные точки находятся из системы dM₁/dθ = 0, dM₂/dθ = 0.
# Для случая 1 ненулевые стационарные решения можно найти,
# решив систему линейных уравнений.

println("\n" * "="^60)
println("СТАЦИОНАРНЫЕ ТОЧКИ (аналитический расчёт)")
println("="^60)

# Расчёт стационарных точек для случая 1
# Система: M₁ - (b/c₁)M₁M₂ - (a₁/c₁)M₁² = 0
#          (c₂/c₁)M₂ - (b/c₁)M₁M₂ - (a₂/c₁)M₂² = 0

# Ненулевое решение (M₁ > 0, M₂ > 0)
# Из первого уравнения: 1 - (b/c₁)M₂ - (a₁/c₁)M₁ = 0
# Из второго: (c₂/c₁) - (b/c₁)M₁ - (a₂/c₁)M₂ = 0

# Решаем систему:
# (a₁/c₁)M₁ + (b/c₁)M₂ = 1
# (b/c₁)M₁ + (a₂/c₁)M₂ = c₂/c₁

# Умножаем на c₁:
# a₁ M₁ + b M₂ = c₁
# b M₁ + a₂ M₂ = c₂

# Решение:
det = a₁ * a₂ - b^2
if det > 0
    M1_star = (c₁ * a₂ - b * c₂) / det
    M2_star = (a₁ * c₂ - b * c₁) / det
    println("\n📈 Стационарные точки (случай 1):")
    println("  M₁* = $(round(M1_star, digits=4))")
    println("  M₂* = $(round(M2_star, digits=4))")
else
    println("\n⚠️ Определитель системы равен нулю или отрицателен")
    println("  Стационарные точки могут отсутствовать")
end

